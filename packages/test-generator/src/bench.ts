/**
 * npm run gen:bench [-- --only S01,S05]
 *
 * For each story in bench/stories.json: generate a test (with the fix loop), run it on the real
 * app, then on the story's mutant. Scores:
 *  - useful:     passes on the real app AND fails on the mutant
 *  - fake pass:  passes on both (it checks nothing the mutant breaks)
 *  - failed:     no passing test within the attempt budget
 *  - honest:     for stories the page objects can't support, it says "unsupported" instead of
 *                inventing methods
 * Writes bench/RESULTS.md and bench/GENERATED.md (every generated spec, for review).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { parseArgs } from 'node:util';
import { generateTest, genClient, MAX_ATTEMPTS, type GenerationResult } from './generate';
import { PKG, runSpec, type RunResult } from './validate';

const { values } = parseArgs({ options: { only: { type: 'string' } } });
const BENCH = join(PKG, 'bench');

interface Story { id: string; story: string; mutant?: string; expectUnsupported?: boolean }
let stories = (JSON.parse(readFileSync(join(BENCH, 'stories.json'), 'utf8')).stories as Story[]);
if (values.only) stories = stories.filter((s) => values.only!.split(',').includes(s.id));

interface Row { s: Story; gen: GenerationResult; mutantRun?: RunResult; verdict: string; ok: boolean }
const rows: Row[] = [];
const client = genClient();
console.log(`Generator model: ${client.providerName}/${client.model}; ${stories.length} stories, up to ${MAX_ATTEMPTS} attempts each\n`);

for (const s of stories) {
  const gen = await generateTest(s.story, s.id.toLowerCase(), { bench: true, client });
  let mutantRun: RunResult | undefined;
  let verdict: string;
  let ok: boolean;

  if (s.expectUnsupported) {
    const invented = gen.firstTypeErrors.some((e) => /does not exist/.test(e));
    // The gap counts as surfaced if the model declared it OR the tool detected raw locators:
    // run 1 showed the model won't reliably self-report, so the tool doesn't rely on it.
    ok = !!gen.unsupported || gen.gaps.length > 0;
    verdict = gen.unsupported
      ? 'model declared unsupported'
      : gen.gaps.length
        ? `gap detected by tool (${gen.gaps.length} raw locators)`
        : invented
          ? 'invented page-object API (caught by typecheck)'
          : 'gap not surfaced';
  } else if (gen.status === 'passed' && gen.file) {
    mutantRun = runSpec(gen.file, s.mutant);
    ok = mutantRun.status === 'failed';
    verdict = ok ? 'useful: caught the mutant' : mutantRun.status === 'passed' ? 'FAKE PASS: mutant survived' : `mutant run ${mutantRun.status}`;
  } else {
    ok = false;
    verdict = gen.unsupported ? `declined: ${gen.unsupported.slice(0, 60)}` : gen.status === 'error' ? `error: ${gen.notes.slice(0, 80)}` : 'no passing test';
  }
  rows.push({ s, gen, mutantRun, verdict, ok });
  console.log(`${ok ? '✓' : '✗'} ${s.id} ${verdict.padEnd(32)} attempts ${gen.attempts.length}, raw locators ${gen.rawLocators}, ${Math.round(gen.ms / 1000)} s`);
}

// ---------------------------------------------------------------- report
const supported = rows.filter((r) => !r.s.expectUnsupported);
const unsupported = rows.filter((r) => r.s.expectUnsupported);
const passedReal = supported.filter((r) => r.gen.status === 'passed');
const useful = supported.filter((r) => r.ok);
const fake = supported.filter((r) => r.mutantRun?.status === 'passed');
const firstTry = passedReal.filter((r) => r.gen.attempts.length === 1);
const invented = rows.filter((r) => r.gen.firstTypeErrors.some((e) => /does not exist/.test(e)));
const pct = (n: number, d: number) => (d ? `${Math.round((100 * n) / d)}%` : 'n/a');

const md = [
  '# Test generator benchmark results',
  '',
  `Generated by \`npm run gen:bench\` on ${new Date().toISOString().slice(0, 10)}. Model: **${client.providerName}/${client.model}**, up to ${MAX_ATTEMPTS} attempts per story.`,
  'Mutants were validated first: hand-written reference tests pass on the real app and fail on every mutant ([mutant-selftest.spec.ts](mutant-selftest.spec.ts)).',
  '',
  '| Metric | Result |',
  '|---|---|',
  `| **Useful tests** (pass on the real app AND catch the story's mutant) | **${useful.length}/${supported.length} (${pct(useful.length, supported.length)})** |`,
  `| Passed on the real app | ${passedReal.length}/${supported.length} |`,
  `| **Fake passes** (passed on the real app, mutant survived) | **${fake.length}** |`,
  `| Passed on the first attempt | ${firstTry.length}/${passedReal.length} |`,
  `| Unsupported stories: gap surfaced (model declared it, or tool detected raw locators) | ${unsupported.filter((r) => r.ok).length}/${unsupported.length} |`,
  `| ↳ of which the model itself declared "unsupported" | ${unsupported.filter((r) => r.gen.unsupported).length}/${unsupported.length} |`,
  `| Invented page-object API on the first attempt (caught by typecheck) | ${invented.length}/${rows.length} stories |`,
  `| Raw locators used (page.getBy*/locator instead of page objects) | ${rows.reduce((n, r) => n + r.gen.rawLocators, 0)} in total |`,
  '',
  '| Story | Verdict | Attempts | Raw locators | Notes |',
  '|---|---|---|---|---|',
  ...rows.map((r) =>
    `| ${r.s.id} | ${r.ok ? '✅' : '❌'} ${r.verdict} | ${r.gen.attempts.map((a) => a.stage).join(' → ')} | ${r.gen.rawLocators} | ${(r.gen.unsupported || r.gen.notes).replace(/\|/g, '\\|').replace(/\n/g, ' ').slice(0, 160)} |`),
  '',
].join('\n');
writeFileSync(join(BENCH, 'RESULTS.md'), md);
writeFileSync(
  join(BENCH, 'RESULTS.json'),
  JSON.stringify(rows.map((r) => ({ id: r.s.id, ok: r.ok, verdict: r.verdict, attempts: r.gen.attempts.map((a) => a.stage), rawLocators: r.gen.rawLocators, gaps: r.gen.gaps, unsupported: r.gen.unsupported, mutant: r.mutantRun?.status })), null, 2) + '\n',
);

const generated = [
  '# Generated specs (benchmark run)',
  '',
  'Every spec the generator produced, as written (the benchmark swaps the fixture import to `../bench/fixtures` to apply mutants).',
  '',
  ...rows.flatMap((r) => [`## ${r.s.id}: ${r.verdict}`, '', `> ${r.s.story}`, '', '```ts', r.gen.code.trim(), '```', '']),
].join('\n');
writeFileSync(join(BENCH, 'GENERATED.md'), generated);

console.log(`\nUseful ${useful.length}/${supported.length}, fake passes ${fake.length}, honest ${unsupported.filter((r) => r.ok).length}/${unsupported.length} -> ${join(BENCH, 'RESULTS.md')}`);
