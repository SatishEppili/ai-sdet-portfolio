/**
 * npm run triage:bench -- [--results test-results-seeded/results.json] [--no-llm]
 *
 * Scores the triage bot against the seeded-failure benchmark (ground truth comes from each
 * test's "expected-category" annotation). Reports the LLM against a signals-only baseline,
 * and writes packages/failure-triage/benchmark/RESULTS.md.
 */
import { existsSync, writeFileSync } from 'node:fs';
import { parseArgs } from 'node:util';
import { LlmClient } from '../../core/src/llm-client';
import { FailureClassifier } from './classifier';
import { readFailures } from './reader';
import { extractSignals, heuristicCategory } from './signals';
import { CATEGORIES, type Category, type Triage } from './types';

const { values } = parseArgs({
  options: {
    results: { type: 'string', default: 'test-results-seeded/results.json' },
    out: { type: 'string', default: 'packages/failure-triage/benchmark/RESULTS.md' },
    'no-llm': { type: 'boolean', default: false },
  },
});

if (!existsSync(values.results!)) {
  console.error(`No ${values.results}. Run "npm run triage:seed" first.`);
  process.exit(1);
}

const cases = readFailures(values.results!).filter((f) => f.expected).sort((a, b) => a.title.localeCompare(b.title));
console.log(`${cases.length} labelled failing/flaky cases (expected 20)`);

const llm = values['no-llm'] ? null : new LlmClient();
const classifier = new FailureClassifier(llm);

interface Row { title: string; expected: Category; baseline: Category; verdict: Triage }
const rows: Row[] = [];
for (const f of cases) {
  const baseline = heuristicCategory(extractSignals(f)).category;
  const verdict = await classifier.classify(f);
  const ok = verdict.category === f.expected ? '✓' : '✗';
  console.log(`${ok} ${f.title.padEnd(48)} expected ${f.expected!.padEnd(12)} got ${verdict.category.padEnd(12)} (baseline ${baseline}, ${verdict.latencyMs ?? 0} ms)`);
  rows.push({ title: f.title, expected: f.expected!, baseline, verdict });
}

const acc = (pick: (r: Row) => Category) => rows.filter((r) => pick(r) === r.expected).length;
const llmCorrect = acc((r) => r.verdict.category);
const baseCorrect = acc((r) => r.baseline);
const pct = (n: number) => `${Math.round((100 * n) / Math.max(rows.length, 1))}%`;
const latencies = rows.map((r) => r.verdict.latencyMs ?? 0).filter(Boolean);
const avgLatency = latencies.length ? Math.round(latencies.reduce((a, b) => a + b, 0) / latencies.length) : 0;
const provider = llm ? `${llm.providerName}` : 'none';

const matrix = [
  `| expected ↓ / predicted → | ${CATEGORIES.join(' | ')} |`,
  `|---|${CATEGORIES.map(() => '---').join('|')}|`,
  ...CATEGORIES.map((e) => `| **${e}** | ${CATEGORIES.map((p) => rows.filter((r) => r.expected === e && r.verdict.category === p).length || '·').join(' | ')} |`),
];
const perClass = CATEGORIES.map((c) => {
  const of = rows.filter((r) => r.expected === c);
  return `| ${c} | ${of.filter((r) => r.verdict.category === c).length}/${of.length} | ${of.filter((r) => r.baseline === c).length}/${of.length} |`;
});

const md = [
  '# Failure-triage benchmark results',
  '',
  `Generated by \`npm run triage:bench\` on ${new Date().toISOString().slice(0, 10)}. Model: **${provider}${llm && process.env.OLLAMA_MODEL && provider === 'ollama' ? ` / ${process.env.OLLAMA_MODEL}` : ''}**.`,
  '',
  `| | Correct | Accuracy |`,
  `|---|---|---|`,
  `| **LLM triage** | ${llmCorrect}/${rows.length} | **${pct(llmCorrect)}** |`,
  `| Signals-only baseline | ${baseCorrect}/${rows.length} | ${pct(baseCorrect)} |`,
  '',
  `Average LLM latency: ${(avgLatency / 1000).toFixed(1)} s per failure.`,
  '',
  '## Per category (LLM vs baseline)',
  '',
  '| Category | LLM | Baseline |',
  '|---|---|---|',
  ...perClass,
  '',
  '## Confusion matrix (LLM)',
  '',
  ...matrix,
  '',
  '## Cases',
  '',
  '| Case | Expected | LLM | Baseline | LLM root cause |',
  '|---|---|---|---|---|',
  ...rows.map((r) =>
    `| ${r.title.replace(/^.*› /, '')} | ${r.expected} | ${r.verdict.category === r.expected ? '✅' : '❌'} ${r.verdict.category} | ${r.baseline === r.expected ? '✅' : '❌'} ${r.baseline} | ${r.verdict.rootCause.replace(/\|/g, '\\|').replace(/\n/g, ' ').slice(0, 220)} |`),
  '',
].join('\n');

writeFileSync(values.out!, md);
writeFileSync(values.out!.replace(/\.md$/, '.json'), JSON.stringify(rows, null, 2));
console.log(`\nLLM ${pct(llmCorrect)} (${llmCorrect}/${rows.length}) vs baseline ${pct(baseCorrect)} -> ${values.out}`);
