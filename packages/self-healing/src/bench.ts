/**
 * npm run heal:bench [-- --no-run]
 *
 * Runs the self-healing benchmark (packages/self-healing/benchmark) and scores it:
 *  - heal rate:       "should heal" cases healed AND the test passed (right element)
 *  - wrong heals:     healed, but the business assertion failed (wrong element)
 *  - false-heal rate: "should refuse" cases that healed anyway (the dangerous one)
 * Writes packages/self-healing/benchmark/RESULTS.md.
 */
import { spawnSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { parseArgs } from 'node:util';
import type { HealResult } from './types';

const { values } = parseArgs({ options: { 'no-run': { type: 'boolean', default: false } } });
const RESULTS = 'test-results-heal/results.json';
const OUT = 'packages/self-healing/benchmark/RESULTS.md';

if (!values['no-run']) {
  spawnSync('npx', ['playwright', 'test', '-c', 'packages/self-healing/benchmark/playwright.config.ts'], {
    stdio: 'inherit', shell: true, env: { ...process.env, SELF_HEAL: 'heal' },
  });
}
if (!existsSync(RESULTS)) {
  console.error(`No ${RESULTS}; the benchmark did not run.`);
  process.exit(1);
}

interface Att { name: string; body?: string }
interface Res { status: string; duration: number; attachments: Att[]; annotations?: { type: string; description?: string }[] }
interface PwTest { annotations: { type: string; description?: string }[]; results: Res[] }
interface Spec { title: string; tests: PwTest[] }
interface Suite { specs?: Spec[]; suites?: Suite[] }

const specs: Spec[] = [];
const walk = (s: Suite) => { specs.push(...(s.specs ?? [])); (s.suites ?? []).forEach(walk); };
(JSON.parse(readFileSync(RESULTS, 'utf8')).suites as Suite[]).forEach(walk);

const decode = (a: Att) => JSON.parse(Buffer.from(a.body ?? '', 'base64').toString('utf8')) as HealResult;

interface Row { id: string; title: string; expected: 'heal' | 'refuse'; passed: boolean; heals: HealResult[]; refusals: HealResult[]; outcome: string; ok: boolean }
const rows: Row[] = specs.map((spec) => {
  const t = spec.tests[0];
  const r = t.results[t.results.length - 1];
  const expected = (t.annotations.find((a) => a.type === 'expected-heal')?.description ?? 'heal') as Row['expected'];
  const heals = r.attachments.filter((a) => a.name === 'self-heal').map(decode);
  const refusals = r.attachments.filter((a) => a.name === 'self-heal-refused').map(decode);
  const passed = r.status === 'passed';
  let outcome: string;
  let ok: boolean;
  if (expected === 'heal') {
    ok = heals.length > 0 && passed;
    outcome = ok ? 'healed correctly' : heals.length ? 'WRONG heal (test failed)' : 'missed (no heal)';
  } else if (heals.length) {
    ok = false;
    outcome = 'FALSE heal';
  } else if (refusals.some((x) => !/LLM unavailable/.test(x.reason))) {
    ok = true;
    outcome = 'refused correctly';
  } else {
    // No decision recorded (or the LLM never answered): don't count it as a success.
    ok = false;
    outcome = 'inconclusive (no heal decision recorded)';
  }
  return { id: spec.title.slice(0, 2), title: spec.title, expected, passed, heals, refusals, outcome, ok };
}).sort((a, b) => a.id.localeCompare(b.id));

const healCases = rows.filter((r) => r.expected === 'heal');
const refuseCases = rows.filter((r) => r.expected === 'refuse');
const healedRight = healCases.filter((r) => r.ok).length;
const wrongHeals = healCases.filter((r) => r.heals.length && !r.passed).length;
const falseHeals = refuseCases.filter((r) => r.heals.length > 0).length;
const inconclusive = rows.filter((r) => r.outcome.startsWith('inconclusive')).length;
const allHeals = rows.flatMap((r) => r.heals);
const byStrategy = (s: string) => allHeals.filter((h) => h.strategy === s).length;
const pct = (n: number, d: number) => (d ? `${Math.round((100 * n) / d)}%` : 'n/a');
const detail = (r: Row) => {
  const h = r.heals[0] ?? r.refusals[0];
  if (!h) return 'no heal attempted';
  return h.ok
    ? `\`${h.testId}\` → \`${h.newLocator}\` (${h.strategy}, similarity ${h.score?.toFixed(2)}, ${h.ms} ms)`
    : `refused \`${h.testId}\`: ${h.reason}`;
};

const md = [
  '# Self-healing benchmark results',
  '',
  `Generated by \`npm run heal:bench\` on ${new Date().toISOString().slice(0, 10)}. LLM for ambiguous cases: **${process.env.LLM_PROVIDER ?? 'ollama'}**.`,
  '',
  '| Metric | Result |',
  '|---|---|',
  `| **Heal rate** (should-heal cases healed onto the right element) | **${healedRight}/${healCases.length} (${pct(healedRight, healCases.length)})** |`,
  `| Wrong heals (healed, but onto the wrong element) | ${wrongHeals}/${healCases.length} |`,
  `| **False-heal rate** (should-refuse cases that healed anyway) | **${falseHeals}/${refuseCases.length} (${pct(falseHeals, refuseCases.length)})** |`,
  `| Heals decided by fingerprint alone / by the LLM | ${byStrategy('fingerprint')} / ${byStrategy('llm')} |`,
  `| Inconclusive (no decision recorded, counted as failures) | ${inconclusive} |`,
  '',
  '| Case | Expected | Outcome | Detail |',
  '|---|---|---|---|',
  ...rows.map((r) => `| ${r.title} | ${r.expected} | ${r.ok ? '✅' : '❌'} ${r.outcome} | ${detail(r).replace(/\|/g, '\\|')} |`),
  '',
].join('\n');

writeFileSync(OUT, md);
console.log(`\nHeal rate ${pct(healedRight, healCases.length)} (${healedRight}/${healCases.length}), wrong heals ${wrongHeals}, false heals ${falseHeals}/${refuseCases.length} -> ${OUT}`);
